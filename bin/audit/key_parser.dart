import 'dart:convert';
import 'dart:io';
import 'package:easy_localization_plus/src/linked_file_resolver.dart';
import 'package:path/path.dart';
import 'package:easy_localization_plus/src/file_loaders/io_file_loader.dart';

/// How a key is used in the code, which tells what it must lead to in the
/// translation files.
enum KeyUsage {
  /// `tr('key')`, `context.tr('key')`, `'key'.tr()`: a text.
  text,

  /// `plural('key', n)`, `'key'.plural(n)`: plural forms (`key.other`...).
  plural,

  /// `tr('key', gender: ...)`: gender forms (`key.male`, `key.female`).
  gender,

  /// `LocaleKeys.key`: the generated keys class also names plural forms,
  /// gender forms and nested keys, so any existing key is valid.
  generatedKey,
}

enum KeyPatternType {
  trFunction(pattern: r"""\btr\s*\(\s*['"]([^'"]+)['"](?:(?!gender\s*:)[^)])*\)""", usage: KeyUsage.text),
  contextTrFunction(
      pattern: r"""context\s*\.\s*tr\s*\(\s*['"]([^'"]+)['"](?:(?!gender\s*:)[^)])*\)""", usage: KeyUsage.text),
  stringTrMethod(pattern: r"""['"]([^'"]+)['"]\s*\.tr\s*\((?:(?!gender\s*:)[^)])*\)""", usage: KeyUsage.text),
  localeKeys(pattern: r"""LocaleKeys\s*\.\s*([A-Za-z0-9_]+)""", usage: KeyUsage.generatedKey),
  // plural
  pluralFunction(pattern: r"""\bplural\s*\(\s*['"]([^'"]+)['"](?:\s*,[^)]*)?\)""", usage: KeyUsage.plural),
  contextPluralFunction(
      pattern: r"""context\s*\.\s*plural\s*\(\s*['"]([^'"]+)['"](?:\s*,[^)]*)?\)""", usage: KeyUsage.plural),
  stringPluralMethod(pattern: r"""['"]([^'"]+)['"]\s*\.plural\s*\(""", usage: KeyUsage.plural),
  // gender
  trFunctionWithGender(
      pattern: r"""\btr\s*\(\s*['"]([^'"]+)['"]\s*,\s*gender\s*:\s*[^)]*\)""", usage: KeyUsage.gender),
  contextTrFunctionWithGender(
      pattern: r"""context\s*\.\s*tr\s*\(\s*['"]([^'"]+)['"]\s*,\s*gender\s*:\s*[^)]*\)""",
      usage: KeyUsage.gender),
  stringTrMethodWithGender(
      pattern: r"""['"]([^'"]+)['"]\s*\.tr\s*\(\s*gender\s*:\s*[^)]*\)""", usage: KeyUsage.gender);

  const KeyPatternType({required this.pattern, required this.usage});

  final String pattern;
  final KeyUsage usage;
}

class KeyParser {
  /// Walks [translationsDir], reads every `.json`, flattens nested maps
  /// into dot‑separated keys, and returns a map:
  ///   { 'en': {'home.title', 'home.subtitle', …}, 'fr': { … } }
  /// Also handles linked translation files (those containing ':/file.json' references)
  Future<Map<String, Set<String>>> parseKeysInTranslationsDir(Directory translationsDir) async {
    final result = <String, Set<String>>{};
    const IOFileLoader fileLoader = IOFileLoader();
    const LinkedFileResolver linkedFileResolver = JsonLinkedFileResolver(fileLoader: fileLoader);

    for (var file in translationsDir.listSync().whereType<File>()) {
      if (!file.path.endsWith('.json')) continue;

      final local = basenameWithoutExtension(file.path);
      final langCode = local.split('-').first;
      final hasCountryCode = local.split('-').length > 1;
      final countryCode = hasCountryCode ? local.split('-').last : null;
      final jsonMap = json.decode(file.readAsStringSync()) as Map<String, dynamic>;

      // Process linked files if present using the shared resolver
      final resolvedJson = await linkedFileResolver.resolveLinkedFiles(
        basePath: translationsDir.path,
        languageCode: langCode,
        baseJson: jsonMap,
        countryCode: countryCode,
      );
      result[local] = _flatten(resolvedJson);
    }
    return result;
  }

  Set<String> _flatten(Map<String, dynamic> json, [String parentKey = '']) {
    final keys = <String>{};
    for (var entry in json.entries) {
      final key = entry.key;
      final value = entry.value;

      final newKey = parentKey.isEmpty ? key : '$parentKey.$key';
      if (value is String) {
        keys.add(newKey);
        continue;
      }

      if (value is Map<String, dynamic>) {
        keys.addAll(_flatten(value, newKey));
        continue;
      }

      if (value is List || value is num || value is bool) {
        keys.add(newKey);
      }
    }
    return keys;
  }

  /// Collects the translation keys used in the `.dart` files of [srcDir],
  /// with how each one is used. A key used through the keys class is kept
  /// as its Dart name, such as `home_title` for `LocaleKeys.home_title`.
  /// [keysClassName] is the name of the class generated by
  /// `generate -f keys` (`LocaleKeys` by default).
  Map<String, Set<KeyUsage>> parseKeysInSourceDir(Directory srcDir, {String keysClassName = 'LocaleKeys'}) {
    final used = <String, Set<KeyUsage>>{};

    List<File> files =
        srcDir.listSync(recursive: true).whereType<File>().where((f) => f.path.endsWith('.dart')).toList();
    for (var file in files) {
      final content = file.readAsStringSync();

      // remove all comments to avoid false positives
      // remove single-line comments that start the line (optionally preceded by whitespace)
      // and multi-line /* ... */ blocks
      final commentPattern = RegExp(
        r'^[ \t]*//.*?$|/\*[\s\S]*?\*/',
        multiLine: true,
      );
      final commentRemovedContent = content.replaceAll(commentPattern, '');

      for (var patternType in KeyPatternType.values) {
        final pattern = patternType == KeyPatternType.localeKeys
            ? RegExp(patternType.pattern
                .replaceFirst('LocaleKeys', r'(?<![A-Za-z0-9_$])' + RegExp.escape(keysClassName)))
            : RegExp(patternType.pattern);
        final matches = pattern.allMatches(commentRemovedContent);

        for (var match in matches) {
          if (match.groupCount > 0) {
            used.putIfAbsent(match.group(1)!, () => <KeyUsage>{}).add(patternType.usage);
          }
        }
      }
    }

    return used;
  }
}
